param(
    [Parameter(Mandatory=$true)][string]$Conllu,
    [string]$Output = (Join-Path $PSScriptRoot '..\data\syntax\zh-gsdsimp-r2.17.inc')
)
$ErrorActionPreference = 'Stop'
$expectedSha256 = '956636FE612A1166E8B19E7413FEE2E73D68231ACA2F0455BE2C616B947D629D'
if ((Get-FileHash -LiteralPath $Conllu -Algorithm SHA256).Hash -ne $expectedSha256) {
    throw 'Use the unmodified Chinese-GSDSimp r2.17 train split (see data/syntax/README.md).'
}
$rows = @{}
$pairs = @{}
$relations = @{
    nsubj = 'subject'; obj = 'object'; iobj = 'object';
    amod = 'modifier'; advmod = 'modifier'; acl = 'modifier'; nmod = 'modifier';
    compound = 'compound'; xcomp = 'complement'; ccomp = 'complement'; clf = 'classifier'
}
function Add-SentencePairs {
    foreach ($token in $rows.Values) {
        $headId = [int]$token[6]
        $childId = [int]$token[0]
        $rel = ($token[7] -split ':', 2)[0]
        if ([Math]::Abs($headId - $childId) -ne 1 -or !$relations.ContainsKey($rel) -or
            !$rows.ContainsKey($headId)) { continue }
        $head = $rows[$headId]
        $left, $right = if ($headId -lt $childId) { $head[1], $token[1] } else { $token[1], $head[1] }
        if ($left -cnotmatch '^[\u3400-\u9FFF]{1,4}$' -or $right -cnotmatch '^[\u3400-\u9FFF]{1,4}$') { continue }
        $key = "$left`t$right"
        if (!$pairs.ContainsKey($key)) { $pairs[$key] = @{} }
        $group = $relations[$rel]
        $pairs[$key][$group] = 1 + $pairs[$key][$group]
    }
    $rows.Clear()
}
foreach ($line in [IO.File]::ReadLines((Resolve-Path -LiteralPath $Conllu).Path)) {
    if (!$line.Length) { Add-SentencePairs; continue }
    if ($line.StartsWith('#')) { continue }
    $token = $line.Split("`t")
    if ($token.Length -eq 10 -and $token[0] -cmatch '^[0-9]+$') { $rows[[int]$token[0]] = $token }
}
Add-SentencePairs
$entries = [Collections.Generic.List[string]]::new()
foreach ($pair in $pairs.GetEnumerator()) {
    $max = 0; $label = ''
    foreach ($name in $pair.Value.Keys) {
        $count = $pair.Value[$name]
        if ($count -gt $max -or ($count -eq $max -and [string]::CompareOrdinal($name, $label) -lt 0)) {
            $max = $count; $label = $name
        }
    }
    $left, $right = $pair.Key.Split("`t")
    if ($max -lt 2 -or ($left.Length -eq 1 -and $right.Length -eq 1 -and $max -lt 4)) { continue }
    $entries.Add(('{{"{0}", "{1}", Relation::{2}, {3}}},' -f $left, $right, $label, $max))
}
$entries.Sort([StringComparer]::Ordinal)
$lines = @('// Derived directional dependency counts. CC BY-SA 4.0; see README.md.', '// Generated by scripts/build-syntax-collocations.ps1.') + $entries.ToArray()
[IO.File]::WriteAllText([IO.Path]::GetFullPath($Output), ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
Write-Output ("Generated {0} dependency pairs." -f $entries.Count)
