"""Extract factual key/glyph mappings and exact APL font outlines, without TeX execution.
The original slot is NOT Unicode identity: modified glyphs have stable W86 IDs.
Requires already available fontTools; installs nothing and performs no networking.
"""
from pathlib import Path
import json
import re
import hashlib
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
ROOT = Path(__file__).resolve().parents[2]
ENV = ROOT / "env/wubi86"
OUT = ROOT / "data/wubi86"


def generate():
    lock = json.loads((OUT / "input-lock.json").read_text(encoding="utf-8"))
    for name, digest in lock.items():
        if hashlib.sha256((ENV / name).read_bytes()).hexdigest() != digest:
            raise ValueError(f"source hash mismatch: {name}")
    font = TTFont(ENV / "rootskb-UMingCN-wubi-86-kb.ttf")
    cmap, glyphs = font.getBestCmap(), font.getGlyphSet()
    upm = font["head"].unitsPerEm
    roots = []
    counts = {}
    for key in "gfdsahjklmtrewqyuiopnbvcx":
        source = (ENV / f"rootskb-kb_{key}.tex").read_text(encoding="utf-8")
        source = re.sub(r"%[^\n]*", "", source)
        slots = []
        for match in re.finditer(r"\\[cC]\s+([^\n]+)", source):
            field = match.group(1).strip()
            if field.startswith("{"):
                # Upstream pads the key-name glyph with 〇 for alignment; not a root.
                field = re.sub(r"^\{\\hskip\s+1em\s+", "", field)
            slots.append(field[0])
        if not slots:
            raise ValueError(f"empty root key: {key}")
        counts[key] = len(slots)
        for index, slot in enumerate(slots, 1):
            if ord(slot) not in cmap:
                raise ValueError(f"missing font glyph: {key}/{slot}")
            pen = SVGPathPen(glyphs)
            glyphs[cmap[ord(slot)]].draw(pen)
            path = pen.getCommands()
            if not path:
                raise ValueError(f"empty glyph path: {key}/{slot}")
            roots.append(dict(id=f"W86-{key}-{index:02d}", key=key,
                              source_slot=f"U+{ord(slot):04X}", path=path))
    inc = "// Generated by tools/wubi86/generate_roots.py; outline license: Arphic-1999.\n"
    for root in roots:
        inc += '{"%s",\'%s\',"%s",R"SVG(%s)SVG"},\n' % (root["id"], root["key"], root["source_slot"], root["path"])
    (ROOT / "src/wubi86/wubi86_roots.inc").write_text(inc, encoding="utf-8")
    (OUT / "roots.json").write_text(json.dumps(dict(units_per_em=upm, key_counts=counts, roots=roots), ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    svg = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1700 2350">',
           '<title>OwO Wubi86 root outlines; Arphic-1999; source-slot identifiers are font-specific</title>',
           '<rect width="1700" height="2350" fill="white"/>']
    for i, key in enumerate(counts):
        x, y = (i % 5)*340, (i // 5)*470
        svg.append(f'<text x="{x+10}" y="{y+25}" font-size="22">{key.upper()}</text>')
        for j, root in enumerate(r for r in roots if r["key"] == key):
            gx, gy = x + (j % 5)*65 + 5, y + (j // 5)*86 + 40
            scale = 55 / upm
            svg.append(f'<g transform="translate({gx},{gy+58}) scale({scale},-{scale})"><path d="{root["path"]}"/></g>')
            svg.append(f'<text x="{gx}" y="{gy+75}" font-size="8">{root["id"]}</text>')
    svg.append('</svg>')
    (OUT / "roots-chart.svg").write_text("\n".join(svg)+"\n", encoding="utf-8")
    # Keep exact source font license, copyright and modification notice with derivative paths.
    (OUT / "LICENSE.roots").write_text(next(n.toUnicode() for n in font["name"].names if n.nameID == 13), encoding="utf-8")
    copyright = next(n.toUnicode() for n in font["name"].names if n.nameID == 0)
    (OUT / "ROOTS-NOTICE.md").write_text("# Root outline attribution\n\n"+copyright+"\n\n"
        "Glyph modifications by riku-ri/wubi-kb: see the retained font-modifications.adoc.\n"
        "OwO conversion: extract the chart's glyphs to SVG paths, assign W86 key-scoped identifiers, "
        "and retain their source-font slots. This is a font-format conversion under Arphic-1999; "
        "no font is installed. SVG paths remain under that license, independently of C++ logic.\n", encoding="utf-8")
    (OUT / "font-modifications.adoc").write_bytes((ENV / "rootskb-font.adoc").read_bytes())
    print("root glyphs", len(roots), "keys", len(counts), counts)


if __name__ == "__main__":
    generate()
